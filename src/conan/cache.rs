use super::graph::Graph;
use crate::{fingerprint::Fingerprint, platform, storage::write_if_changed};
use anyhow::Result;
use serde::{Deserialize, Serialize};
use serde_json::Value;
use std::{
    collections::BTreeSet,
    fs,
    path::{Path, PathBuf},
};

pub(super) const FILE: &str = "cppm-install.json";
const FORMAT: u32 = 3;

#[derive(Deserialize, Serialize)]
pub(super) struct Cached {
    format: u32,
    key: String,
    /// Fingerprint of everything Conan would read to produce `key`. A match
    /// proves `key` is still current without starting Conan.
    #[serde(default)]
    fast: Option<String>,
    /// The Conan home this installation was resolved in.
    pub home: PathBuf,
    pub lock: Value,
    pub graph: Value,
    generated: String,
    packages: String,
}

impl Cached {
    fn is_current(&self, output: &Path, previous: Option<&Value>) -> bool {
        self.format == FORMAT
            && Some(&self.lock) == previous
            && output.join("conan_toolchain.cmake").is_file()
            && output.join("cppm-runtime.json").is_file()
            && generated(output).ok().as_deref() == Some(self.generated.as_str())
            && packages(&self.graph).ok().flatten().as_deref() == Some(self.packages.as_str())
    }
}

/// The inputs of a dependency installation that are known before Conan runs.
pub(super) struct Request<'a> {
    pub root: &'a Path,
    pub profile: &'a str,
    pub store_dir: Option<&'a Path>,
    pub release: bool,
    pub cpp_standard: u8,
    pub recipe: &'a str,
}

fn home_state(value: &mut Fingerprint, home: &Path) -> Result<()> {
    value.os(home.as_os_str());
    for file in [
        "global.conf",
        "settings.yml",
        "settings_user.yml",
        "editable_packages.json",
    ] {
        value.file(&home.join(file))?;
    }
    // Custom hooks and compatibility plugins can change a dependency graph.
    // Ignore Python's generated bytecode, whose mtimes/content are irrelevant.
    value.directory(&home.join("extensions"), "__pycache__")
}

pub(super) fn key(home: &Path, version: &str, recipe: &str, profiles: &[u8]) -> Result<String> {
    let mut value = Fingerprint::new("conan-install-v1");
    value.add(version.as_bytes());
    value.add(recipe.as_bytes());
    value.add(profiles);
    value.environment()?;
    home_state(&mut value, home)?;
    Ok(value.finish())
}

/// Describes, without starting Conan, everything `key` is derived from: the
/// Conan executable, the selected home and the profile files. `None` means
/// those inputs cannot be enumerated safely (a profile using Jinja can read
/// anything), so Conan must be asked.
pub(super) fn fast_key(request: &Request, home: &Path) -> Result<Option<String>> {
    let Some(conan) = platform::find_executable("conan").and_then(|path| path.canonicalize().ok())
    else {
        return Ok(None);
    };
    let Some(profiles) = profile_files(home, request.root, request.profile) else {
        return Ok(None);
    };
    let mut value = Fingerprint::new("conan-fast-v1");
    // Package managers rewrite the launcher when Conan is installed/upgraded.
    value.os(conan.as_os_str());
    let launcher = fs::metadata(&conan)?;
    value.add(&launcher.len().to_le_bytes());
    value.add(format!("{:?}", launcher.modified()?).as_bytes());
    // Conan records the version that last migrated this home.
    value.file(&home.join("version.txt"))?;
    value.add(request.profile.as_bytes());
    value.add(&[u8::from(request.release), request.cpp_standard]);
    value.add(request.recipe.as_bytes());
    // The home is selected by --store-dir, CONAN_HOME or a .conanrc file in a
    // parent directory; the user's home directory is part of the environment.
    match request.store_dir {
        Some(directory) => value.os(directory.as_os_str()),
        None => value.add(b"default store"),
    }
    match std::env::var_os("CONAN_HOME") {
        Some(directory) => value.os(&directory),
        None => value.add(b"no CONAN_HOME"),
    }
    for directory in std::env::current_dir()?.ancestors() {
        let file = directory.join(".conanrc");
        if file.is_file() {
            value.file(&file)?;
        }
    }
    value.environment()?;
    home_state(&mut value, home)?;
    for profile in profiles {
        value.file(&profile)?;
    }
    Ok(Some(value.finish()))
}

/// The selected profile and every profile it includes, following Conan's
/// lookup order. `None` when a profile is missing or is a Jinja template.
fn profile_files(home: &Path, root: &Path, profile: &str) -> Option<BTreeSet<PathBuf>> {
    fn locate(home: &Path, base: &Path, name: &str) -> Option<PathBuf> {
        let path = Path::new(name);
        let candidate = if path.is_absolute() {
            path.to_path_buf()
        } else if name.starts_with("./") || name.starts_with(".\\") || name.starts_with("..") {
            base.join(path)
        } else {
            let shared = home.join("profiles").join(path);
            if shared.exists() {
                shared
            } else {
                base.join(path)
            }
        };
        candidate.is_file().then_some(candidate)
    }
    fn visit(home: &Path, file: PathBuf, files: &mut BTreeSet<PathBuf>) -> Option<()> {
        // Include cycles are a Conan error; let Conan report them.
        if files.len() > 64 {
            return None;
        }
        let source = fs::read_to_string(&file).ok()?;
        if source.contains("{{") || source.contains("{%") {
            return None;
        }
        let base = file.parent()?.to_path_buf();
        if !files.insert(file) {
            return Some(());
        }
        for line in source.lines() {
            if let Some(name) = line
                .trim()
                .strip_prefix("include(")
                .and_then(|rest| rest.strip_suffix(')'))
            {
                visit(home, locate(home, &base, name.trim())?, files)?;
            }
        }
        Some(())
    }
    let mut files = BTreeSet::new();
    visit(home, locate(home, root, profile)?, &mut files)?;
    Some(files)
}

fn load(output: &Path) -> Option<Cached> {
    serde_json::from_slice(&fs::read(output.join(FILE)).ok()?).ok()
}

/// Reuse validated against the profiles resolved by Conan.
pub(super) fn read(output: &Path, key: &str, previous: Option<&Value>) -> Option<Cached> {
    load(output).filter(|cached| cached.key == key && cached.is_current(output, previous))
}

/// Reuse validated without starting Conan. The caller locks `home` first, so
/// packages cannot be removed between this check and their registration.
pub(super) fn read_fast(
    output: &Path,
    request: &Request,
    previous: Option<&Value>,
    lock: impl FnOnce(&Path) -> Option<fs::File>,
) -> Option<(Cached, fs::File)> {
    let cached = load(output)?;
    let expected = cached.fast.as_deref()?;
    if cached.format != FORMAT
        || fast_key(request, &cached.home).ok().flatten().as_deref() != Some(expected)
    {
        return None;
    }
    let guard = lock(&cached.home)?;
    cached
        .is_current(output, previous)
        .then_some((cached, guard))
}

pub(super) struct Snapshot<'a> {
    pub key: String,
    pub fast: Option<String>,
    pub home: &'a Path,
    pub lock: &'a Value,
    pub graph: &'a Value,
}

pub(super) fn save(output: &Path, snapshot: Snapshot) -> Result<()> {
    let Some(packages) = packages(snapshot.graph)? else {
        return Ok(());
    };
    let cached = Cached {
        format: FORMAT,
        key: snapshot.key,
        fast: snapshot.fast,
        home: snapshot.home.to_path_buf(),
        lock: snapshot.lock.clone(),
        graph: metadata(snapshot.graph),
        generated: generated(output)?,
        packages,
    };
    write_if_changed(&output.join(FILE), &serde_json::to_vec(&cached)?)
}

/// The last resolved graph of this configuration, for read-only commands
/// such as `list` and `why`. It may be older than cppm.toml.
pub(crate) fn graph(output: &Path) -> Option<(Value, Value)> {
    load(output)
        .filter(|cached| cached.format == FORMAT)
        .map(|cached| (cached.graph, cached.lock))
}

fn metadata(graph: &Value) -> Value {
    // Keep only data used for CMake mapping, package validation and store
    // registration. Conan's full report also includes unrelated environments
    // and configuration; retaining it wastes space and may persist user values.
    let mut nodes = serde_json::Map::new();
    if let Some(entries) = graph["graph"]["nodes"].as_object() {
        for (id, node) in entries {
            let mut properties = serde_json::Map::new();
            for name in [
                "name",
                "version",
                "context",
                "ref",
                "recipe",
                "recipe_folder",
                "package_folder",
                "package_id",
                "prev",
                "python_requires",
                "cpp_info",
                // Options select recipe-specific CMake fixes; edges and
                // licenses serve `list`, `why` and `licenses` offline.
                "options",
                "dependencies",
                "license",
            ] {
                if let Some(value) = node.get(name) {
                    properties.insert(name.into(), value.clone());
                }
            }
            nodes.insert(id.clone(), Value::Object(properties));
        }
    }
    serde_json::json!({"graph": {"nodes": nodes}})
}

fn generated(output: &Path) -> Result<String> {
    let mut value = Fingerprint::new("conan-generators-v1");
    value.directory(output, FILE)?;
    Ok(value.finish())
}

fn packages(graph: &Value) -> Result<Option<String>> {
    let graph = Graph::new(graph);
    if !graph.is_present() {
        return Ok(None);
    }
    let mut value = Fingerprint::new("conan-packages-v1");
    for node in graph.nodes() {
        // Editable recipes can depend on arbitrary external source trees.
        if node.is_editable() {
            return Ok(None);
        }
        if let Some(folder) = node.package_folder() {
            let manifest = Path::new(folder).join("conanmanifest.txt");
            if !manifest.is_file() {
                return Ok(None);
            }
            value.file(&manifest)?;
        }
        if let Some(folder) = node.recipe_folder()
            && !node.is_consumer()
        {
            let recipe = Path::new(folder).join("conanfile.py");
            if !recipe.is_file() {
                return Ok(None);
            }
            value.file(&recipe)?;
        }
    }
    Ok(Some(value.finish()))
}

#[cfg(test)]
mod tests {
    use super::*;
    use serde_json::json;

    #[test]
    fn stale_generators_missing_packages_and_lock_changes_require_installation() {
        let temp = tempfile::tempdir().unwrap();
        let output = temp.path().join("generated");
        let package = temp.path().join("package");
        fs::create_dir(&output).unwrap();
        fs::create_dir(&package).unwrap();
        fs::write(output.join("conan_toolchain.cmake"), "toolchain").unwrap();
        fs::write(output.join("cppm-runtime.json"), "{}").unwrap();
        let manifest = package.join("conanmanifest.txt");
        fs::write(&manifest, "package revision").unwrap();
        let graph = json!({"graph": {"nodes": {"1": {
            "recipe": "Cache", "package_folder": package,
            "name": "sdl", "version": "3.4.16", "context": "host", "license": "Zlib",
            "options": {"shared": "False", "wayland": "True"},
            "dependencies": {"2": {"direct": true}},
            "runenv_info": {"PRIVATE_VALUE": "do-not-cache-user-environment"},
            "cpp_info": {"root": {"properties": {"cmake_target_name": "Package::Package"}}}
        }}}});
        let lock = json!({"requires": ["package/1.0#revision"]});
        let snapshot = || Snapshot {
            key: "profile".into(),
            fast: None,
            home: temp.path(),
            lock: &lock,
            graph: &graph,
        };
        save(&output, snapshot()).unwrap();
        assert!(
            !fs::read_to_string(output.join(FILE))
                .unwrap()
                .contains("do-not-cache-user-environment")
        );
        assert_eq!(
            read(&output, "profile", Some(&lock)).unwrap().graph["graph"]["nodes"]["1"]["cpp_info"],
            graph["graph"]["nodes"]["1"]["cpp_info"]
        );
        // A reused installation must generate the same recipe-specific CMake
        // fixes as a fresh one; those are selected by package options.
        let reused = read(&output, "profile", Some(&lock)).unwrap().graph;
        assert_eq!(
            crate::packages::cmake_fixes(&reused),
            crate::packages::cmake_fixes(&graph)
        );
        let node = &reused["graph"]["nodes"]["1"];
        assert_eq!(node["license"], "Zlib");
        assert_eq!(node["dependencies"]["2"]["direct"], true);
        assert!(read(&output, "changed profile", Some(&lock)).is_none());
        assert!(read(&output, "profile", Some(&json!({}))).is_none());
        fs::write(output.join("conan_toolchain.cmake"), "modified toolchain").unwrap();
        assert!(read(&output, "profile", Some(&lock)).is_none());
        fs::write(output.join("conan_toolchain.cmake"), "toolchain").unwrap();
        assert!(read(&output, "profile", Some(&lock)).is_some());
        fs::remove_file(&manifest).unwrap();
        assert!(read(&output, "profile", Some(&lock)).is_none());
        fs::write(&manifest, "different package revision").unwrap();
        assert!(read(&output, "profile", Some(&lock)).is_none());
    }

    #[test]
    fn registering_an_editable_recipe_invalidates_an_installed_graph() {
        let home = tempfile::tempdir().unwrap();
        let previous = key(home.path(), "Conan 2", "recipe", b"profiles").unwrap();
        fs::write(
            home.path().join("editable_packages.json"),
            r#"{"package/1.0":{"path":"local-source"}}"#,
        )
        .unwrap();
        let editable = key(home.path(), "Conan 2", "recipe", b"profiles").unwrap();
        assert_ne!(previous, editable);
        fs::remove_file(home.path().join("editable_packages.json")).unwrap();
        assert_eq!(
            previous,
            key(home.path(), "Conan 2", "recipe", b"profiles").unwrap()
        );
    }

    fn request<'a>(root: &'a Path, profile: &'a str, recipe: &'a str) -> Request<'a> {
        Request {
            root,
            profile,
            store_dir: None,
            release: false,
            cpp_standard: 20,
            recipe,
        }
    }

    #[test]
    fn fast_key_follows_included_profiles_and_gives_up_on_templates() {
        // The key needs a Conan launcher in PATH, like the real command.
        let Some(_conan) = platform::find_executable("conan") else {
            return;
        };
        let temp = tempfile::tempdir().unwrap();
        let home = temp.path().join("home");
        let root = temp.path().join("project");
        fs::create_dir_all(home.join("profiles")).unwrap();
        fs::create_dir(&root).unwrap();
        fs::write(home.join("profiles/default"), "[settings]\nos=Linux\n").unwrap();
        fs::write(root.join("team"), "include(./base)\n").unwrap();
        fs::write(root.join("base"), "include(default)\n[conf]\n").unwrap();
        let key = |profile: &str, recipe: &str| {
            fast_key(&request(&root, profile, recipe), &home).unwrap()
        };
        let default = key("default", "recipe").unwrap();
        assert_eq!(key("default", "recipe").as_ref(), Some(&default));
        assert_ne!(key("default", "another recipe").as_ref(), Some(&default));
        let team = key("./team", "recipe").unwrap();
        assert_ne!(team, default);
        // An edit two includes away, and one in the home, both invalidate.
        fs::write(
            root.join("base"),
            "include(default)\n[conf]\ntools.build:jobs=2\n",
        )
        .unwrap();
        let edited = key("./team", "recipe").unwrap();
        assert_ne!(edited, team);
        fs::write(home.join("profiles/default"), "[settings]\nos=Macos\n").unwrap();
        assert_ne!(key("./team", "recipe").unwrap(), edited);
        fs::write(home.join("global.conf"), "tools.build:jobs=1\n").unwrap();
        assert_ne!(key("default", "recipe").unwrap(), default);
        // Templates may read anything; a missing include is Conan's error.
        fs::write(root.join("base"), "{% set jobs = 2 %}\n").unwrap();
        assert!(key("./team", "recipe").is_none());
        fs::write(root.join("base"), "include(missing)\n").unwrap();
        assert!(key("./team", "recipe").is_none());
        assert!(key("missing", "recipe").is_none());
    }

    #[test]
    fn fast_reuse_needs_a_matching_key_and_a_current_installation() {
        let Some(_conan) = platform::find_executable("conan") else {
            return;
        };
        let temp = tempfile::tempdir().unwrap();
        let home = temp.path().join("home");
        let output = temp.path().join("generated");
        let package = temp.path().join("package");
        for directory in [&home.join("profiles"), &output, &package] {
            fs::create_dir_all(directory).unwrap();
        }
        fs::write(home.join("profiles/default"), "[settings]\n").unwrap();
        fs::write(output.join("conan_toolchain.cmake"), "toolchain").unwrap();
        fs::write(output.join("cppm-runtime.json"), "{}").unwrap();
        fs::write(package.join("conanmanifest.txt"), "revision").unwrap();
        let graph =
            json!({"graph": {"nodes": {"1": {"recipe": "Cache", "package_folder": package}}}});
        let lock = json!({"requires": ["package/1.0#revision"]});
        let request = request(temp.path(), "default", "recipe");
        let guard = |_: &Path| fs::File::open(temp.path()).ok();
        let store = |fast| {
            save(
                &output,
                Snapshot {
                    key: "slow".into(),
                    fast,
                    home: &home,
                    lock: &lock,
                    graph: &graph,
                },
            )
            .unwrap()
        };
        // Without a recorded fast key Conan must be consulted.
        store(None);
        assert!(read_fast(&output, &request, Some(&lock), guard).is_none());
        store(fast_key(&request, &home).unwrap());
        assert!(read_fast(&output, &request, Some(&lock), guard).is_some());
        assert!(read_fast(&output, &request, Some(&json!({})), guard).is_none());
        // Failing to lock the store is a miss, never an unlocked reuse.
        assert!(read_fast(&output, &request, Some(&lock), |_| None).is_none());
        fs::write(package.join("conanmanifest.txt"), "rebuilt").unwrap();
        assert!(read_fast(&output, &request, Some(&lock), guard).is_none());
        fs::write(package.join("conanmanifest.txt"), "revision").unwrap();
        fs::write(home.join("profiles/default"), "[settings]\nos=Linux\n").unwrap();
        assert!(read_fast(&output, &request, Some(&lock), guard).is_none());
    }
}
