//! Read-only view of the dependency graph reported by Conan.
//!
//! Conan's JSON report is kept verbatim (it is persisted in snapshots and the
//! lockfile), but every module used to index it by hand. This view is the one
//! place that knows the report's shape.

use serde_json::Value;

#[derive(Clone, Copy)]
pub struct Graph<'a>(&'a Value);

#[derive(Clone, Copy)]
pub struct Node<'a> {
    pub id: &'a str,
    value: &'a Value,
}

/// An edge to another node of the same graph.
#[derive(Clone, Copy)]
pub struct Edge<'a> {
    pub id: &'a str,
    pub direct: bool,
    pub build: bool,
    pub test: bool,
}

impl<'a> Graph<'a> {
    pub fn new(report: &'a Value) -> Self {
        Self(report)
    }

    /// `None` when the report has no graph at all (a dependency-free project).
    pub fn is_present(self) -> bool {
        self.0["graph"]["nodes"].is_object()
    }

    pub fn nodes(self) -> impl Iterator<Item = Node<'a>> {
        self.0["graph"]["nodes"]
            .as_object()
            .into_iter()
            .flatten()
            .map(|(id, value)| Node { id, value })
    }

    pub fn node(self, id: &str) -> Option<Node<'a>> {
        self.0["graph"]["nodes"]
            .as_object()?
            .get_key_value(id)
            .map(|(id, value)| Node { id, value })
    }

    /// The package linked into the application, as opposed to a build tool.
    pub fn host(self, name: &str) -> Option<Node<'a>> {
        self.nodes()
            .find(|node| node.name() == Some(name) && node.is_host())
    }

    /// The consumer recipe generated by cppm.
    pub fn root(self) -> Option<Node<'a>> {
        self.nodes().find(Node::is_consumer)
    }
}

impl<'a> Node<'a> {
    fn text(&self, field: &str) -> Option<&'a str> {
        self.value[field].as_str()
    }

    pub fn name(&self) -> Option<&'a str> {
        self.text("name")
    }

    pub fn version(&self) -> Option<&'a str> {
        self.text("version")
    }

    /// `name/version#recipe-revision`, or the consumer's file name.
    pub fn reference(&self) -> Option<&'a str> {
        self.text("ref")
    }

    pub fn recipe(&self) -> Option<&'a str> {
        self.text("recipe")
    }

    pub fn binary(&self) -> Option<&'a str> {
        self.text("binary")
    }

    pub fn package_id(&self) -> Option<&'a str> {
        self.text("package_id")
    }

    pub fn package_revision(&self) -> Option<&'a str> {
        self.text("prev")
    }

    pub fn package_folder(&self) -> Option<&'a str> {
        self.text("package_folder")
    }

    pub fn recipe_folder(&self) -> Option<&'a str> {
        self.text("recipe_folder")
    }

    pub fn is_host(&self) -> bool {
        self.value["context"] == "host"
    }

    pub fn is_consumer(&self) -> bool {
        matches!(self.recipe(), Some("Consumer" | "Cli" | "Virtual"))
    }

    pub fn is_editable(&self) -> bool {
        self.recipe() == Some("Editable")
    }

    /// Recipes declare one license or a list of them.
    pub fn licenses(&self) -> Vec<&'a str> {
        match &self.value["license"] {
            Value::String(license) => vec![license.as_str()],
            Value::Array(licenses) => licenses.iter().filter_map(Value::as_str).collect(),
            _ => Vec::new(),
        }
    }

    /// Conan reports options as strings ("True"); older reports used booleans.
    pub fn option_is(&self, name: &str, expected: bool) -> bool {
        let value = &self.value["options"][name];
        value == &Value::Bool(expected)
            || value.as_str() == Some(if expected { "True" } else { "False" })
    }

    pub fn python_requires(&self) -> impl Iterator<Item = &'a str> {
        self.value["python_requires"]
            .as_object()
            .into_iter()
            .flat_map(|requires| requires.keys().map(String::as_str))
    }

    pub fn cmake_property(&self, name: &str) -> Option<&'a str> {
        self.value["cpp_info"]["root"]["properties"][name].as_str()
    }

    pub fn edges(&self) -> impl Iterator<Item = Edge<'a>> {
        self.value["dependencies"]
            .as_object()
            .into_iter()
            .flatten()
            .map(|(id, edge)| Edge {
                id,
                direct: edge["direct"] == true,
                build: edge["build"] == true,
                test: edge["test"] == true,
            })
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use serde_json::json;

    #[test]
    fn nodes_expose_recipe_metadata_and_tolerate_missing_fields() {
        let report = json!({"graph": {"nodes": {
            "0": {"recipe": "Consumer", "ref": "conanfile.py", "context": "host",
                  "dependencies": {"1": {"direct": true}, "2": {"direct": false}}},
            "1": {"name": "fmt", "version": "11.0.2", "context": "host", "recipe": "Cache",
                  "license": "MIT", "options": {"shared": "False", "header_only": true},
                  "python_requires": {"helper/1.0#rev": {}},
                  "cpp_info": {"root": {"properties": {"cmake_target_name": "fmt::fmt"}}}},
            "2": {"name": "fmt", "version": "11.0.2", "context": "build", "license": ["MIT", "BSL-1.0"]}
        }}});
        let graph = Graph::new(&report);
        assert!(graph.is_present());
        assert_eq!(graph.nodes().count(), 3);
        let root = graph.root().unwrap();
        assert_eq!(root.id, "0");
        assert_eq!(root.edges().filter(|edge| edge.direct).count(), 1);
        // Build-context tools never shadow the library linked into the app.
        let fmt = graph.host("fmt").unwrap();
        assert_eq!(fmt.id, "1");
        assert_eq!(fmt.licenses(), ["MIT"]);
        assert!(fmt.option_is("shared", false) && fmt.option_is("header_only", true));
        assert!(!fmt.option_is("missing", false));
        assert_eq!(fmt.cmake_property("cmake_target_name"), Some("fmt::fmt"));
        assert_eq!(
            fmt.python_requires().collect::<Vec<_>>(),
            ["helper/1.0#rev"]
        );
        assert_eq!(graph.node("2").unwrap().licenses(), ["MIT", "BSL-1.0"]);
        assert!(graph.host("missing").is_none());
        let empty = Value::Null;
        assert!(!Graph::new(&empty).is_present());
        assert_eq!(Graph::new(&empty).nodes().count(), 0);
    }
}
